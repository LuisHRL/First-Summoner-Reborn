#if UNITY_EDITOR
using System;
using System.Linq;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.UI;

/// <summary>Idempotent, explicit installer. Never deletes gameplay UI or changes Slider references.</summary>
public static class CombatUIInstaller
{
    [MenuItem("Tools/First Summoner/Combat UI/Install Animated UI")]
    public static void Install()
    {
        const string scenePath = "Assets/Scenes/GameScene.unity";
        var scene = EditorSceneManager.OpenScene(scenePath, OpenSceneMode.Single);
        var playerUI = UnityEngine.Object.FindObjectsByType<PlayerUI>(FindObjectsInactive.Include).FirstOrDefault();
        if (playerUI == null || playerUI.manaBar == null)
        {
            Debug.LogError("[Combat UI] PlayerUI or ManaBar missing. No changes made.");
            return;
        }
        Undo.IncrementCurrentGroup();
        var manaSlider = playerUI.manaBar;
        var barFill = manaSlider.fillRect != null ? manaSlider.fillRect.GetComponent<Image>() : null;
        if (barFill == null)
        {
            Debug.LogError("[Combat UI] ManaBar Slider Fill Image missing. No changes made.");
            return;
        }
        // The Slider changes its fill RectTransform every frame; animate a separate overlay.
        var manaVisual = EnsureImage(barFill.transform.parent, "AnimatedManaVisual", barFill.sprite);
        Stretch(manaVisual.rectTransform);
        manaVisual.color = new Color(0.92f, 0.42f, 1f, 1f);
        ConfigureFill(manaVisual, Image.FillMethod.Horizontal);
        manaVisual.rectTransform.SetAsLastSibling();
        // Migrate the icon generated by earlier installer versions (old parent was the panel).
        var oldIcon = manaSlider.transform.parent.Find("AnimatedManaIcon");
        if (oldIcon != null && manaSlider.transform.Find("AnimatedManaIcon") == null)
            Undo.SetTransformParent(oldIcon, manaSlider.transform, "Migrate animated mana icon");
        if (barFill.enabled) { Undo.RecordObject(barFill, "Hide Slider driven visual"); barFill.enabled = false; }
        var manaAnimation = EnsureAnimation(manaSlider.transform, "AnimatedManaBar", manaVisual, null, false);
        var manaIconSprite = FindSprite("icon_mana");
        var manaIcon = EnsureImage(manaSlider.transform, "AnimatedManaIcon", manaIconSprite);
        var iconRect = manaIcon.rectTransform;
        iconRect.anchorMin = new Vector2(0, 0.5f);
        iconRect.anchorMax = new Vector2(0, 0.5f);
        iconRect.pivot = new Vector2(0, 0.5f);
        iconRect.anchoredPosition = new Vector2(4, 0);
        if (manaIconSprite != null) iconRect.sizeDelta = manaIconSprite.rect.size;
        // Preserve the original white mana icon without tint or rotation.
        manaIcon.color = new Color(0.30f, 0.12f, 0.42f, 1f);
        // Preserve the original icon orientation; only the transition light rotates.
        iconRect.localRotation = Quaternion.identity;
        manaIcon.gameObject.SetActive(true);
        // Clip the animated fill and its moving light to the original vial silhouette.
        var vialMask = manaIcon.GetComponent<Mask>();
        if (vialMask == null) vialMask = Undo.AddComponent<Mask>(manaIcon.gameObject);
        vialMask.showMaskGraphic = true;
        if (manaIconSprite == null)
            Debug.LogError("[Combat UI] icon_mana not found in atlas; vial sprite missing.");
        var iconFill = EnsureImage(manaIcon.transform, "ManaIconFill", manaIcon.sprite);
        Stretch(iconFill.rectTransform);
        // A white fill must remain brighter than the unfilled silhouette.
        iconFill.color = new Color(1f, 0.82f, 1f, 1f);
        ConfigureFill(iconFill, Image.FillMethod.Vertical);
        var iconAnimation = EnsureAnimation(manaIcon.transform, "AnimatedManaIconFill", iconFill, null, true);
        iconFill.fillOrigin = (int)Image.OriginVertical.Bottom;
        iconAnimation.instantResetFromFullToEmpty = true;
        EditorUtility.SetDirty(iconAnimation);
        var gain = EnsureImage(manaIcon.transform, "ManaGainFx", FindSprite("icon_mana_fx"));
        if (gain.sprite != null) gain.rectTransform.sizeDelta = gain.sprite.rect.size;
        gain.rectTransform.anchorMin = gain.rectTransform.anchorMax = new Vector2(0.5f, 0.5f);
        gain.rectTransform.pivot = new Vector2(0.5f, 0.5f);
        gain.rectTransform.anchoredPosition = Vector2.zero;
        gain.raycastTarget = false;
        gain.gameObject.SetActive(false);
        Undo.RecordObject(playerUI, "Wire mana animation");
        playerUI.manaBarAnimation = manaAnimation;
        playerUI.manaIconAnimation = iconAnimation;
        playerUI.manaGainFx = gain;
        EditorUtility.SetDirty(playerUI);
        Debug.Log("[Combat UI] Mana sprites: vial=" + (manaIcon.sprite != null ? manaIcon.sprite.name : "MISSING")
            + ", gain=" + (gain.sprite != null ? gain.sprite.name : "MISSING")
            + ", vial light=" + (iconAnimation.transitionLight != null ? iconAnimation.transitionLight.sprite.name : "MISSING")
            + ", bar light=" + (manaAnimation.transitionLight != null ? manaAnimation.transitionLight.sprite.name : "MISSING"));

        // Target UI: retain existing target tracking, replace only fill visuals.
        var target = UnityEngine.Object.FindObjectsByType<TargetHealthBarUI>(FindObjectsInactive.Include).FirstOrDefault();
        if (target != null && target.healthBarFill != null)
        {
            var hpFill = target.healthBarFill;
            var hpSprite = FindSprite("img_bar_hp");
            if (hpSprite != null) { Undo.RecordObject(hpFill, "HP sprite"); hpFill.sprite = hpSprite; hpFill.color = new Color(0.52f, 0.12f, 0.16f, 1f); }
            ConfigureFill(hpFill, Image.FillMethod.Horizontal);
            var targetBackground = hpFill.transform.parent.GetComponent<Image>();
            if (targetBackground == null)
                targetBackground = Undo.AddComponent<Image>(hpFill.transform.parent.gameObject);
            var targetFrameSprite = FindSprite("img_bar_hp_bg");
            if (targetBackground != null && targetFrameSprite != null)
            {
                targetBackground.sprite = targetFrameSprite;
                ConfigureProportionalFrame(targetBackground, targetFrameSprite);
            }
            var hit = EnsureImage(hpFill.transform.parent, "HPDamageTrail", FindSprite("img_bar_hp_hit"));
            hit.rectTransform.SetSiblingIndex(hpFill.transform.GetSiblingIndex() + 1);
            CopyRect(hpFill.rectTransform, hit.rectTransform);
            ConfigureHitVisual(hit, hpFill);
            RemoveGeneratedFrame(hpFill.transform.parent, "TargetHPFrameOutline");
            var hpAnimation = EnsureAnimation(hpFill.transform.parent, "AnimatedTargetHP", hpFill, hit, false);
            hpAnimation.flashRemainingHealthOnDamage = true;
            hpAnimation.persistentLightBelowFullHealth = true;
            EditorUtility.SetDirty(hpAnimation);
            Undo.RecordObject(target, "Wire target HP animation");
            target.healthAnimation = hpAnimation;
            Debug.Log("[Combat UI] Target HP light=" + (hpAnimation.transitionLight != null ? hpAnimation.transitionLight.sprite.name : "MISSING"));
            EditorUtility.SetDirty(target);
        }
        EditorSceneManager.MarkSceneDirty(scene);
        EditorSceneManager.SaveScene(scene);

        // Prefab is configured independently, since enemy bars are spawned dynamically.
        const string prefabPath = "Assets/Prefabs/UI/EnemyHealthBar.prefab";
        var prefab = PrefabUtility.LoadPrefabContents(prefabPath);
        try
        {
            var enemyBar = prefab.GetComponent<EnemyHealthBar>();
            var hpFill = prefab.transform.Find("HealthBarBackground/HealthBarFill")?.GetComponent<Image>();
            if (enemyBar != null && hpFill != null)
            {
                var hpSprite = FindSprite("img_bar_hp");
                if (hpSprite != null) { hpFill.sprite = hpSprite; hpFill.color = Color.white; }
                ConfigureFill(hpFill, Image.FillMethod.Horizontal);
                // The original enemy frame is a horizontally sliced sprite. Keep the
                // prefab dimensions and its inset fill; render the frame above the fill.
                var background = hpFill.transform.parent.GetComponent<Image>();
                var frameSprite = FindSprite("img_bar_hp_bg");
                if (background != null && frameSprite != null)
                {
                    background.sprite = frameSprite;
                    ConfigureProportionalFrame(background, frameSprite);
                }
                var hit = EnsureImage(hpFill.transform.parent, "HPDamageTrail", FindSprite("img_bar_hp_hit"));
                CopyRect(hpFill.rectTransform, hit.rectTransform);
                hit.rectTransform.SetSiblingIndex(hpFill.transform.GetSiblingIndex() + 1);
                ConfigureHitVisual(hit, hpFill);
                RemoveGeneratedFrame(hpFill.transform.parent, "EnemyHPFrameOutline");
                enemyBar.healthBarFill = hpFill;
                enemyBar.healthAnimation = EnsureAnimation(hpFill.transform.parent, "AnimatedEnemyHP", hpFill, hit, false);
                enemyBar.healthAnimation.flashRemainingHealthOnDamage = true;
                enemyBar.healthAnimation.persistentLightBelowFullHealth = true;
                Debug.Log("[Combat UI] Enemy HP light=" + (enemyBar.healthAnimation.transitionLight != null ? enemyBar.healthAnimation.transitionLight.sprite.name : "MISSING"));
                PrefabUtility.SaveAsPrefabAsset(prefab, prefabPath);
            }
        }
        finally { PrefabUtility.UnloadPrefabContents(prefab); }
        AssetDatabase.SaveAssets();
        Debug.Log("[Combat UI] Animated UI installed. Existing sliders, player HP and card mana icons preserved. Missing sprites use fallback visuals.");
    }

    private static AnimatedFillEffect EnsureAnimation(Transform parent, string name, Image fill, Image trail, bool vertical)
    {
        var t = parent.Find(name);
        GameObject go;
        if (t == null) { go = new GameObject(name, typeof(RectTransform)); Undo.RegisterCreatedObjectUndo(go, name); go.transform.SetParent(parent, false); }
        else go = t.gameObject;
        var animation = go.GetComponent<AnimatedFillEffect>();
        if (animation == null) animation = Undo.AddComponent<AnimatedFillEffect>(go);
        animation.fill = fill;
        animation.delayedFill = trail;
        // The atlas light orientation differs from the logical fill axis.
        // Preserve the existing HP light and correct the vial light by 90 degrees.
        animation.horizontalLight = vertical;
        var light = EnsureImage(fill.transform.parent, name + "Light", FindSprite("fx_light_03"));
        light.rectTransform.SetAsLastSibling();
        RectTransform fillRect = fill.rectTransform;
        float thickness = Mathf.Max(2f, Mathf.Min(fillRect.rect.width, fillRect.rect.height) * 0.18f);
        light.rectTransform.sizeDelta = vertical && light.sprite != null
            ? light.sprite.rect.size
            : new Vector2(thickness, Mathf.Max(1f, fillRect.rect.height));
        light.raycastTarget = false;
        light.gameObject.SetActive(false);
        if (light.sprite == null && fill.sprite != null) light.sprite = fill.sprite;
        light.type = Image.Type.Simple;
        light.color = vertical ? new Color(1f, 1f, 1f, 0.9f) : new Color(1f, 0.6f, 0.55f, 0.75f);
        animation.transitionLight = light.sprite != null ? light : null;
        EditorUtility.SetDirty(animation);
        return animation;
    }

    private static void ConfigureProportionalFrame(Image frame, Sprite sprite)
    {
        frame.sprite = sprite;
        frame.type = Image.Type.Sliced;
        frame.fillCenter = true;
        frame.color = Color.white;
        frame.raycastTarget = false;

        // Unity's default sliced-image border uses pixels per unit. At a
        // different UI height, the end caps can become flattened. Derive the
        // multiplier from the sprite's own height and the existing frame height
        // so its corners retain their original aspect ratio; only the middle
        // section stretches horizontally.
        var rect = frame.rectTransform;
        float height = rect.rect.height;
        if (height <= 0f) height = Mathf.Abs(rect.sizeDelta.y);
        if (height <= 0f || sprite.pixelsPerUnit <= 0f) return;
        var canvas = frame.canvas;
        float referencePPU = canvas != null ? canvas.referencePixelsPerUnit : 100f;
        frame.pixelsPerUnitMultiplier =
            sprite.rect.height * referencePPU / (height * sprite.pixelsPerUnit);
        EditorUtility.SetDirty(frame);
    }

    private static void RemoveGeneratedFrame(Transform parent, string name)
    {
        // Only remove our obsolete generated overlay, never the original HP UI.
        for (int i = parent.childCount - 1; i >= 0; i--)
        {
            var child = parent.GetChild(i);
            if (child.name != name || child.childCount != 0) continue;
            if (child.GetComponents<Component>().Any(c =>
                c != null && !(c is Transform) && !(c is CanvasRenderer) && !(c is Image)))
                continue;
            Undo.DestroyObjectImmediate(child.gameObject);
        }
    }

    private static void RemoveDuplicateGeneratedChildren(Transform parent, string generatedName)
    {
        bool found = false;
        for (int i = parent.childCount - 1; i >= 0; i--)
        {
            var child = parent.GetChild(i);
            if (child.name != generatedName) continue;
            if (!found) { found = true; continue; }
            // A duplicate generated frame has no gameplay component or child objects.
            if (child.childCount != 0 || child.GetComponents<Component>().Any(c =>
                c != null && !(c is Transform) && !(c is CanvasRenderer) && !(c is Image)))
                continue;
            Undo.DestroyObjectImmediate(child.gameObject);
        }
    }

    private static Image EnsureImage(Transform parent, string name, Sprite sprite)
    {
        var t = parent.Find(name);
        GameObject go;
        if (t == null) { go = new GameObject(name, typeof(RectTransform), typeof(CanvasRenderer), typeof(Image)); Undo.RegisterCreatedObjectUndo(go, name); go.transform.SetParent(parent, false); }
        else go = t.gameObject;
        var image = go.GetComponent<Image>();
        if (image == null) image = Undo.AddComponent<Image>(go);
        if (sprite != null) image.sprite = sprite;
        image.raycastTarget = false;
        EditorUtility.SetDirty(image);
        return image;
    }

    private static Sprite FindSprite(string name)
    {
        // The original UI sprites are sub-assets of the z_total atlas.
        const string atlasPath = "Assets/Generated/AssetRipperSprites/Sprite_Atlas_UI_z_total.png";
        var atlasSprite = AssetDatabase.LoadAllAssetsAtPath(atlasPath)
            .OfType<Sprite>().FirstOrDefault(sprite => sprite.name == name);
        if (atlasSprite != null) return atlasSprite;
        foreach (var guid in AssetDatabase.FindAssets(name + " t:Texture2D"))
        {
            string path = AssetDatabase.GUIDToAssetPath(guid);
            var match = AssetDatabase.LoadAllAssetsAtPath(path).OfType<Sprite>().FirstOrDefault(s => s.name == name);
            if (match != null) return match;
        }
        foreach (var guid in AssetDatabase.FindAssets("t:Sprite"))
        {
            string path = AssetDatabase.GUIDToAssetPath(guid);
            var match = AssetDatabase.LoadAllAssetsAtPath(path).OfType<Sprite>().FirstOrDefault(s => s.name == name);
            if (match != null) return match;
        }
        Debug.LogWarning("[Combat UI] Sprite not found: " + name + " (existing graphic retained where possible)");
        return null;
    }

    private static void ConfigureHitVisual(Image hit, Image original)
    {
        if (hit.sprite == null) hit.sprite = original.sprite;
        hit.color = new Color(1f, 0.34f, 0.38f, 1f);
        ConfigureFill(hit, Image.FillMethod.Horizontal);
        hit.raycastTarget = false;
    }

    private static void ConfigureFill(Image image, Image.FillMethod method)
    {
        image.type = Image.Type.Filled;
        image.fillMethod = method;
        image.fillOrigin = 0;
        image.fillAmount = 1f;
    }
    private static void Stretch(RectTransform rect)
    {
        rect.anchorMin = Vector2.zero; rect.anchorMax = Vector2.one;
        rect.offsetMin = Vector2.zero; rect.offsetMax = Vector2.zero;
    }
    private static void CopyRect(RectTransform source, RectTransform dest)
    {
        dest.anchorMin = source.anchorMin; dest.anchorMax = source.anchorMax;
        dest.pivot = source.pivot; dest.anchoredPosition = source.anchoredPosition;
        dest.sizeDelta = source.sizeDelta;
    }
}
